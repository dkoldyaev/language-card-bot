import { test, expect } from '@playwright/test';
import { register, login, addWordsToDictionary } from './helpers';

test.describe('Dictionary Operations', () => {
  test.beforeEach(async ({ page }, testInfo) => {
    page.on('console', msg => {
      if (msg.type() === 'error') {
        console.log(`[PAGE ERROR LOG]: ${msg.text()}`);
      }
    });
    page.on('pageerror', error => console.log(`[PAGE ERROR]: ${error.message}`));

    const username = `testuser_dict_${Date.now()}_${testInfo.workerIndex}`;
    await register(page, username);
    await login(page, username);
  });

  test('should navigate to Dictionary, add words, and verify them', async ({ page }) => {
    test.setTimeout(90000);
    // 1. Add words using the helper function
    const wordsToAdd = ['apple', 'banana'];
    await addWordsToDictionary(page, wordsToAdd);

    // 2. Reload the dictionary page (it's already the unified page)
    await page.goto('/dictionary');
    await expect(page.locator('text=Vocabulary Deck')).toBeVisible();

    // 3. Verify that the added words are displayed in the list and have correct definitions
    for (const word of wordsToAdd) {
      await expect(async () => {
        // Reload the page to re-fetch dictionary if definitions are not ready
        await page.reload();
        await expect(page.locator('text=Vocabulary Deck')).toBeVisible();

        const wordAccordion = page.locator('.MuiAccordion-root').filter({ hasText: word });
        await expect(wordAccordion).toBeVisible();
        
        // Ensure that the accordion shows "2 definition(s)" to avoid expanding prematurely
        await expect(wordAccordion).toContainText('2 definition(s)');

        // Expand the accordion to see definitions
        await wordAccordion.locator('.MuiAccordionSummary-root').click();
        
        // Verify mock definitions are present
        await expect(wordAccordion.locator(`text=[Mock] Definition 1 for ${word} in ru`).first()).toBeVisible();
        await expect(wordAccordion.locator(`text=[Mock] Definition 2 for ${word} in ru`).first()).toBeVisible();
        
        // Verify mock translations are present
        await expect(wordAccordion.locator(`text=Translation: [MOCK: ru -> en] [Mock] Definition 1 for ${word} in ru`)).toBeVisible();
        await expect(wordAccordion.locator(`text=Translation: [MOCK: ru -> en] [Mock] Definition 2 for ${word} in ru`)).toBeVisible();
      }).toPass();

      // Edit Definition 1
      const wordAccordion = page.locator('.MuiAccordion-root').filter({ hasText: word });
      await wordAccordion.locator('button[aria-label="Edit definition"]').first().click();
      await wordAccordion.locator('input[type="text"]').fill(`Edited definition for ${word}`);
      await wordAccordion.locator('button:has-text("Save")').click();

      // Wait for the UI update to guarantee the PUT request has completed before we reload
      await expect(wordAccordion.locator(`text=1. Edited definition for ${word}`)).toBeVisible();

      // Wait for the new translation to be generated by the worker
      await expect(async () => {
        await page.reload();
        await expect(page.locator('text=Vocabulary Deck')).toBeVisible();
        const acc = page.locator('.MuiAccordion-root').filter({ hasText: word });
        await expect(acc).toBeVisible();
        await acc.locator('.MuiAccordionSummary-root').click();
        
        await expect(acc.locator(`text=1. Edited definition for ${word}`)).toBeVisible();
        await expect(acc.locator(`text=Translation: [MOCK: ru -> en] Edited definition for ${word}`)).toBeVisible();
      }).toPass({ timeout: 30000 });

      // Now edit the translation directly
      const updatedAccordion = page.locator('.MuiAccordion-root').filter({ hasText: word });
      await updatedAccordion.locator('button[aria-label="Edit translation"]').first().click();
      await updatedAccordion.locator('input[type="text"]').fill(`Manually edited translation for ${word}`);
      await updatedAccordion.locator('button:has-text("Save")').click();

      await expect(updatedAccordion.locator(`text=Translation: Manually edited translation for ${word}`)).toBeVisible();

      // Delete the second definition
      page.once('dialog', dialog => dialog.accept());
      await updatedAccordion.locator('button[aria-label="Delete definition"]').last().click();
      
      // Wait for it to disappear
      await expect(updatedAccordion.locator(`text=[Mock] Definition 2 for ${word} in ru`).first()).not.toBeVisible();
      
      // Verify the accordion shows 1 definition remaining
      await expect(updatedAccordion).toContainText('1 definition(s)');

      // Delete the word itself
      page.once('dialog', dialog => dialog.accept());
      await updatedAccordion.locator(`[aria-label="Delete ${word}"]`).click();

      // Verify the word disappears
      await expect(updatedAccordion).not.toBeVisible();
    }

    // After deleting all words, the dictionary should be empty
    await expect(page.locator('text=Your dictionary is empty.')).toBeVisible();
  });

  test('should switch dictionaries in Dictionary page without altering active learning language', async ({ page }) => {
    test.setTimeout(60000);
    await page.goto('/dictionary');
    await expect(page.locator('text=Vocabulary Deck')).toBeVisible();

    // Top-right selector represents the active learning language
    const headerSelector = page.locator('[data-testid="dictionary-selector-button"]');
    await expect(headerSelector).toBeVisible();
    await expect(headerSelector).toContainText('EN (RU)');

    // Verify initial dictionary has ACTIVE badge in the in-page switcher
    const pageSwitcher = page.locator('[data-testid="dictionary-page-switcher"]');
    await expect(pageSwitcher.locator('text=ACTIVE')).toBeVisible();

    // Create a new dictionary
    await page.click('button:has-text("New Dictionary")');
    await expect(page.locator('h2:has-text("Create New Dictionary")')).toBeVisible();

    await page.fill('input[name="name"], input[placeholder*="Spanish"], input[type="text"]:visible >> nth=0', 'Spanish Vocab');
    await page.click('button:has-text("Create Dictionary")');

    // Both dictionaries should be visible in page switcher, and Spanish Vocab is selected
    const spanishTab = pageSwitcher.locator('button:has-text("Spanish Vocab")');
    await expect(spanishTab).toBeVisible();

    // CRITICAL: Top-right corner selector must NOT change (active learning language is preserved)
    await expect(headerSelector).toContainText('EN (RU)');
    await expect(headerSelector).not.toContainText('Spanish');

    // Initial dictionary still has the ACTIVE badge in page switcher
    await expect(pageSwitcher.locator('text=ACTIVE')).toBeVisible();

    // The header for AddWordForm indicates Spanish Vocab
    await expect(page.locator('text=Add words to Spanish Vocab')).toBeVisible();

    // Add a word to Spanish Vocab
    await page.fill('textarea', 'hola');
    await page.click('button:has-text("Submit Words")');
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'hola' })).toBeVisible();

    // Switch back to the first dictionary (which has ACTIVE chip) in page switcher
    const activeDictBtn = pageSwitcher.locator('button:has(.MuiChip-root:has-text("ACTIVE"))');
    await activeDictBtn.click();

    // In the first dictionary, "hola" should NOT be present
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'hola' })).not.toBeVisible();

    // CRITICAL: Top-right corner selector still unchanged
    await expect(headerSelector).toContainText('EN (RU)');
    await expect(headerSelector).not.toContainText('Spanish');
  });

  test('should only select visible words when filtering with search and clicking All', async ({ page }) => {
    test.setTimeout(60000);
    const wordsToAdd = ['apple', 'apricot', 'banana'];
    await addWordsToDictionary(page, wordsToAdd);

    await page.goto('/dictionary');
    await expect(page.locator('text=Vocabulary Deck')).toBeVisible();

    // Verify all 3 words are visible initially
    for (const word of wordsToAdd) {
      await expect(page.locator('.MuiAccordion-root').filter({ hasText: word })).toBeVisible();
    }

    // Filter by "ap"
    const searchInput = page.getByPlaceholder('Search words...');
    await searchInput.fill('ap');

    // Only apple and apricot should be visible
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'apple' })).toBeVisible();
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'apricot' })).toBeVisible();
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'banana' })).not.toBeVisible();

    // Click "All" checkbox
    await page.locator('label:has-text("All")').click();

    // Only the 2 visible words should be selected
    const deleteButton = page.locator('button:has-text("Delete (2)")');
    await expect(deleteButton).toBeVisible();

    // Clear the filter
    await searchInput.clear();

    // Banana reappears, but selection count should still be 2
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'banana' })).toBeVisible();
    await expect(deleteButton).toBeVisible();

    // Bulk delete the selected 2 words
    page.once('dialog', dialog => dialog.accept());
    await deleteButton.click();

    // Verify apple and apricot were deleted, but banana remains
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'apple' })).not.toBeVisible();
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'apricot' })).not.toBeVisible();
    await expect(page.locator('.MuiAccordion-root').filter({ hasText: 'banana' })).toBeVisible();
  });

  test('should allow editing dictionary name with pencil icon and contenteditable', async ({ page }) => {
    test.setTimeout(60000);
    await page.goto('/dictionary');
    await expect(page.locator('text=Vocabulary Deck')).toBeVisible();

    const heading = page.locator('h1');

    // Pencil button is visible
    const editBtn = page.locator('[data-testid="edit-dictionary-title-btn"]');
    await expect(editBtn).toBeVisible();
    await editBtn.click();

    // Heading is now contenteditable
    await expect(heading).toHaveAttribute('contenteditable', 'true');
    const saveBtn = page.locator('[data-testid="save-dictionary-title-btn"]');
    const cancelBtn = page.locator('[data-testid="cancel-dictionary-title-btn"]');
    await expect(saveBtn).toBeVisible();
    await expect(cancelBtn).toBeVisible();

    // Fill new name and save
    const newName = 'Renamed Deck';
    await heading.fill(newName);
    await saveBtn.click();

    // Heading updated and no longer editable
    await expect(heading).toHaveText(newName);
    await expect(heading).not.toHaveAttribute('contenteditable', 'true');

    // In-page switcher tab also reflects the new name
    const pageSwitcher = page.locator('[data-testid="dictionary-page-switcher"]');
    await expect(pageSwitcher.locator(`button:has-text("${newName}")`)).toBeVisible();

    // Reload page to verify persistence
    await page.reload();
    await expect(page.locator('h1')).toHaveText(newName);
  });
});

